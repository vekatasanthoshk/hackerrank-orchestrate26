"""Compare two extractions of the PNG / PDF evidence (model comparison).

    python3 code/evaluation/compare_media.py

After `python3 code/main.py --refresh-media`, `code/cache/media/` holds the vision model's
extraction and `code/cache/media_manual/` the earlier development-time transcription. This
script diffs them field by field (resource ids, identifiers, state flags) and writes the
result to `code/evaluation/media_comparison.md`, which evaluation_report.md links to.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.dirname(HERE)
MODEL_DIR = os.path.join(CODE, "cache", "media")
MANUAL_DIR = os.path.join(CODE, "cache", "media_manual")
FIELDS = ("system", "email", "phone", "customer_reference", "enabled", "restore_allowed", "result")


def _norm(v):
    return None if v in (None, "", "null") else str(v).strip().lower()


def _key(rec):
    return rec.get("resource_id") or "alias:" + ",".join(sorted(rec.get("aliases") or []))


def _load(folder, name):
    with open(os.path.join(folder, name), encoding="utf-8") as fh:
        return {_key(r): r for r in json.load(fh).get("records", [])}


def main():
    if not os.path.isdir(MANUAL_DIR):
        print("no code/cache/media_manual/ - run `python3 code/main.py --refresh-media` first")
        return 1
    lines = ["# Media extraction comparison", "",
             "Vision model (`code/cache/media/`) vs development-time transcription "
             "(`code/cache/media_manual/`). Generated by `code/evaluation/compare_media.py`.", "",
             "| file | records (model / manual) | matched | field agreement | differences |",
             "|---|---|---|---|---|"]
    tot_fields = tot_agree = tot_model = tot_manual = tot_match = 0
    for name in sorted(os.listdir(MANUAL_DIR)):
        if not name.endswith(".json") or not os.path.exists(os.path.join(MODEL_DIR, name)):
            continue
        model, manual = _load(MODEL_DIR, name), _load(MANUAL_DIR, name)
        matched = sorted(set(model) & set(manual))
        diffs, agree, n = [], 0, 0
        for k in matched:
            for f in FIELDS:
                n += 1
                a, b = _norm(model[k].get(f)), _norm(manual[k].get(f))
                if a == b:
                    agree += 1
                else:
                    diffs.append(f"{k}.{f}: model={a} manual={b}")
        only = [f"+model {k}" for k in sorted(set(model) - set(manual))] + \
               [f"-model {k}" for k in sorted(set(manual) - set(model))]
        tot_fields, tot_agree = tot_fields + n, tot_agree + agree
        tot_model, tot_manual, tot_match = tot_model + len(model), tot_manual + len(manual), tot_match + len(matched)
        detail = "; ".join(only + diffs) or "-"
        lines.append(f"| {name[:-5]} | {len(model)} / {len(manual)} | {len(matched)} | "
                     f"{agree}/{n} | {detail} |")
    lines += ["", f"**Totals:** {tot_match} records matched of {tot_model} (model) / {tot_manual} (manual); "
                  f"field agreement {tot_agree}/{tot_fields}"
                  f" ({(tot_agree / tot_fields * 100) if tot_fields else 0:.1f}%).", ""]
    out = os.path.join(HERE, "media_comparison.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines[-2:]))
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
