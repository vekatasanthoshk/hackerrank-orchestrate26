"""Generate code/evaluation/usage_report.md from the run ledger of the last full run.

    python3 code/evaluation/usage_report.py

Inputs: cache/last_run.json (written by main.py) and cache/usage_ledger.jsonl
(one row per real API response, with the ``usage`` token counts). Media extraction
calls from earlier runs are reported separately because their cached output is
re-used, not re-billed, by the final run.
"""
import json
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.dirname(HERE)
PRICES = {  # USD per 1M tokens (input, output), Anthropic first-party rates
    "claude-haiku-5-5": (0.10, 0.50),
    "claude-sonnet-5-5": (2.00, 10.00),
    "claude-opus-5-5": (4.00, 20.00),
}


def cost(model, tin, tout):
    pin, pout = PRICES.get(model, (0, 0))
    return tin / 1e6 * pin + tout / 1e6 * pout


def main():
    run = json.load(open(os.path.join(CODE, "cache", "last_run.json")))
    ledger_path = os.path.join(CODE, "cache", "usage_ledger.jsonl")
    rows = [json.loads(l) for l in open(ledger_path)] if os.path.exists(ledger_path) else []
    this_run = [r for r in rows if r["run_id"] == run["run_id"]]
    earlier_media = [r for r in rows if r["run_id"] != run["run_id"] and r["purpose"] == "media_extraction"]
    n = max(run["requests"], 1)
    texts = sum(run["intent"].get(k, 0) for k in ("llm_calls", "cache_hits", "rule_only"))

    per = defaultdict(lambda: {"calls": 0, "in": 0, "out": 0})
    for r in this_run:
        k = (r["model"], r["purpose"])
        per[k]["calls"] += 1
        per[k]["in"] += r["input_tokens"]
        per[k]["out"] += r["output_tokens"]
    tot_calls = sum(v["calls"] for v in per.values())
    tot_in = sum(v["in"] for v in per.values())
    tot_out = sum(v["out"] for v in per.values())
    tot_cost = sum(cost(m, v["in"], v["out"]) for (m, _), v in per.items())

    L = ["# Token usage and cost report", "",
         "Generated by `python3 code/evaluation/usage_report.py` from `code/cache/last_run.json` and the",
         "per-call ledger `code/cache/usage_ledger.jsonl` (every API response's `usage` block is appended",
         "there by `code/ledger.py`). Numbers below are measured, not estimated, unless marked *projection*.", "",
         "## Final full-dataset run", "",
         f"- run id: `{run['run_id']}` (finished {run['finished_at']})",
         f"- input: `{run['requests_file']}` -> `{run['output_file']}`; {run['requests']} requests",
         f"- statuses: {', '.join(f'{k} {v}' for k, v in sorted(run['statuses'].items()))}",
         f"- LLM intent classification enabled: **{run['llm_enabled']}** "
         f"over {texts} distinct request texts "
         f"(llm calls {run['intent'].get('llm_calls', 0)}, cache hits {run['intent'].get('cache_hits', 0)}, "
         f"rule-only {run['intent'].get('rule_only', 0)}, LLM-vs-rule disagreements {run['intent_disagreements']})",
         f"- media evidence: {run['media_cache_files']} PNG/PDF artifacts served from `code/cache/media/` "
         f"({run['media_observations']} extracted records); 0 vision calls in this run", "",
         "## Provider / model totals (this run)", "",
         "| Provider | Model | Purpose | Calls | Input tokens | Output tokens | Total tokens | Est. cost (USD) |",
         "|---|---|---|---|---|---|---|---|"]
    for (m, p), v in sorted(per.items()):
        L.append(f"| Anthropic | `{m}` | {p} | {v['calls']} | {v['in']:,} | {v['out']:,} | {v['in'] + v['out']:,} | "
                 f"${cost(m, v['in'], v['out']):.4f} |")
    L.append(f"| **All** | | | **{tot_calls}** | **{tot_in:,}** | **{tot_out:,}** | **{tot_in + tot_out:,}** | "
             f"**${tot_cost:.4f}** |")
    L += ["", "| Per request (averaged over all requests) | Value |", "|---|---|",
          f"| model calls / request | {tot_calls / n:.3f} |",
          f"| tokens / request | {(tot_in + tot_out) / n:.1f} |",
          f"| cost / request (USD) | ${tot_cost / n:.6f} |", ""]
    if earlier_media:
        mi = sum(r["input_tokens"] for r in earlier_media)
        mo = sum(r["output_tokens"] for r in earlier_media)
        mm = earlier_media[0]["model"]
        L += ["## One-time media extraction (cached, re-used by every run)", "",
              f"{len(earlier_media)} vision calls on `{mm}`: {mi:,} input + {mo:,} output tokens, "
              f"${cost(mm, mi, mo):.4f}.", ""]
    L += ["## Notes", "",
          "- Deterministic stages (ingestion of SQL/JSON/logs/text, identity resolution, as-of state, policy,",
          "  planning) use no model at all, so model cost does not grow with evidence volume.",
          "- Intent results are cached per request text (SHA-256), so re-runs re-use them (`cache hits`).",
          "- Prices: Haiku 5.5 $0.10 / $0.50, Sonnet 5.5 $2 / $10, Opus 5.5 $4 / $20 per 1M input / output tokens.",
          ""]
    if tot_calls == 0:
        L += ["### Why this run made zero model calls", "",
              "No `ANTHROPIC_API_KEY` was available in the build environment, so the run used the cached",
              "media extractions and the deterministic multilingual rule classifier for intent (the",
              "documented fallback in `code/intent.py`). With a key set, `python3 code/main.py` classifies",
              "each distinct request text once with `claude-haiku-5-5` and this report is regenerated with",
              "the measured numbers.", "",
              "*Projection* for a keyed run (prompt is ~430 tokens + request text ~60 tokens; JSON answer",
              f"~40 tokens plus low-effort thinking): one call per distinct text = {texts} calls x ~500 input /",
              f"~150 output tokens = ~{texts * 500:,} input + ~{texts * 150:,} output tokens, about "
              f"${cost('claude-haiku-5-5', texts * 500, texts * 150):.3f} total "
              f"(~${cost('claude-haiku-5-5', texts * 500, texts * 150) / n:.6f} per request over {run['requests']} requests).",
              ""]
    out = os.path.join(HERE, "usage_report.md")
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main()
